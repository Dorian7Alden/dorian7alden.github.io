#!/usr/bin/env bash
# ============================================================
# 一键启动测试：串行 Step 1→2→3→4，本地快速配置。
#
# 设计目标：本地快速迭代，测出可信的性能趋势，而非 OJ 精确值。
# 参数固定，队员之间结果可直接横向对比。
#
# 参数选择理由：
#   -w 20         W=20，约 1000 万行数据，够大能反映真实性能，又不会像 W=50 生成太久
#   -t 8          8 线程，保守值，8 核机器也能稳定跑，避免线程过载干扰结果
#   --warmup 30   预热 30s，让 buffer pool 和索引缓存热起来，测量更稳定
#   --measure 60  测量 60s，比 OJ 的 360s 短，但足够让 tpmC 收敛到一个可信区间
#   -r 1          只跑 1 轮，快速出结果。多轮中位数需要完整 3 轮才有意义，本地没必要
#   --keep-data   复用已有数据，避免每次重新生成 W=20 数据（首次会自动生成）
#   --suite quick 集成测试只跑冒烟+崩溃恢复，覆盖核心正确性即可
# ============================================================
set -euo pipefail
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

exec bash "$SCRIPT_DIR/cli.sh" \
  --all \
  --suite full \
  -w 20 \
  -t 8 \
  --warmup 30 \
  --measure 60 \
  -r 1 \
  --keep-data
